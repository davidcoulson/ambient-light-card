#!/usr/bin/env python3
"""Emit every addressable_lambda effect of the given YAML files as C++ for addressable_flash_test.cpp.

    addressable_cases.py FILE.yaml [FILE.yaml ...] > out.h

Each effect becomes namespace fxN { run(...) } as the YAML text has it, plus a table fx_cases[] of {name, interval_ms,
ring?, run}. update_interval is the effect's own, so the test drives it at the rate
the light would.
"""
import re
import sys


def lambda_body(lines, i):
    """The lambda: |- block after the effect's name line i."""
    for j in range(i + 1, len(lines)):
        lm = re.match(r"(\s*)lambda:\s*\|-?\s*$", lines[j])
        if lm:
            indent, body = len(lm.group(1)), []
            for s in lines[j + 1:]:
                if s.strip() and len(s) - len(s.lstrip(" ")) <= indent:
                    break
                body.append(s)
            return "\n".join(body)
    sys.exit(f"addressable_cases: no lambda after line {i + 1}")


cases = []
print("// Generated by addressable_cases.py - do not edit.")
for path in sys.argv[1:]:
    lines = open(path).read().splitlines()
    for i, l in enumerate(lines):
        m = re.match(r"\s*name:\s*\"(.*)\"\s*$", l)
        if not (m and re.match(r"\s*-\s*addressable_lambda:\s*$", lines[i - 1])):
            continue
        ms = 20
        for j in range(i + 1, min(i + 4, len(lines))):
            u = re.match(r"\s*update_interval:\s*(\d+)ms", lines[j])
            if u:
                ms = int(u.group(1))
        n = len(cases)
        body = lambda_body(lines, i).replace('sync_offset("${mac}")', "FX_TEST_OFFSET").replace('"${mac}"', "FX_TEST_MAC")
        # what ESPHome's lambda parser does: id(x). is x->, and the substitutions are text
        body = body.replace("id(accent_light).", "accent_light->").replace("id(accent_light)", "accent_light")
        body = body.replace("${ht_fire_x}", "0.5").replace("${ht_fire_y}", "0.5")
        print(f"namespace fx{n} {{\n// {m.group(1)}\ninline void run(FxIt &it, Color current_color, bool initial_run) {{\n{body}\n}}\n}}\n")
        cases.append((m.group(1), ms, n, "ht2d" in path))
print("static const FxCase fx_cases[] = {")
for name, ms, n, ht in cases:
    print(f'  {{"{name}", {ms}, {"true" if ht else "false"}, fx{n}::run}},')
print("};")
