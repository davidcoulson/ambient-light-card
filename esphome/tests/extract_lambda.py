#!/usr/bin/env python3
"""Pull effect lambdas out of an effects YAML file as C++ functions, for the host tests.

    extract_lambda.py FILE.yaml NAME=EFFECT [NAME=EFFECT ...] > out.h

Each NAME=EFFECT emits `namespace NAME { void run(...) { <the lambda body> } }`,
with the signature ESPHome gives that kind of effect:
    addressable_lambda   run(FxIt &it, Color current_color, bool initial_run)
    lambda               run(bool initial_run)
Extract one effect under two names to get two independent lights: each copy has
its own statics, as two devices would.

The body is the YAML text as it is, with two test hooks swapped in:
  - "${mac}" becomes FX_TEST_MAC, and sync_offset("${mac}") becomes
    FX_TEST_OFFSET, so a test can pick which voice or offset a light has
    (mac_hash32 caches the first MAC it sees, so one process could not
    otherwise be two lights);
  - an assignment whose target is listed in FX_PROBES below has its value
    passed through fx_probe("target", value) first, so a test can see what a
    simulation stored without the effect being changed to expose it.
A missing effect, or a probe that matches nothing, is an error.

    extract_lambda.py --all PREFIX FILE.yaml > out.h

emits every plain `lambda` effect in the file as namespace PREFIX0, PREFIX1 ...
and a table `PREFIX_cases[]` of {name, run} (struct FxCase, declared by the
including test) in file order. Addressable lambdas are skipped.
"""
import re
import sys

# effect name -> assignment targets to probe
FX_PROBES = {
    "Fireworks Burst": ["p_vel[i]", "p_hue[i]"],
}


def find_lambda(lines, effect):
    for i, line in enumerate(lines):
        m = re.match(r"(\s*)name:\s*\"(.*)\"\s*$", line)
        if not m or m.group(2) != effect:
            continue
        kind_line = lines[i - 1]
        kind = re.match(r"\s*-\s*(addressable_lambda|lambda):\s*$", kind_line)
        if not kind:
            sys.exit(f"extract_lambda: '{effect}' is not a lambda effect")
        for j in range(i + 1, len(lines)):
            lm = re.match(r"(\s*)lambda:\s*\|-?\s*$", lines[j])
            if lm:
                indent = len(lm.group(1))
                body = []
                for k in range(j + 1, len(lines)):
                    s = lines[k]
                    if s.strip() and len(s) - len(s.lstrip(" ")) <= indent:
                        break
                    body.append(s)
                return kind.group(1), body
        break
    sys.exit(f"extract_lambda: no effect named '{effect}'")


def emit(ns, effect, kind, body, subs):
    text = "\n".join(body)
    for k, v in subs.items():
        text = text.replace("${" + k + "}", v)
    text = text.replace('sync_offset("${mac}")', "FX_TEST_OFFSET").replace('"${mac}"', "FX_TEST_MAC")
    text = re.sub(r"\bid\((\w+)\)\.", r"id(\1)->", text)   # as ESPHome turns id(x).y into x->y
    sig = "FxIt &it, Color current_color, bool initial_run" if kind == "addressable_lambda" else "bool initial_run"
    print(f"namespace {ns} {{\n// {effect}\ninline void run({sig}) {{\n{text}\n}}\n}}  // namespace {ns}\n")


def all_plain(prefix, path):
    lines = open(path).read().splitlines()
    subs = dict(re.findall(r'^  (\w+): "([^"$]*)"', "\n".join(lines), re.M))   # the file's own substitution defaults
    names = [m.group(1) for i, l in enumerate(lines) if (m := re.match(r"\s*name:\s*\"(.*)\"\s*$", l))
             and re.match(r"\s*-\s*lambda:\s*$", lines[i - 1])]
    print("// Generated by extract_lambda.py --all from " + path.split("/")[-1] + " - do not edit.")
    for n, effect in enumerate(names):
        emit(f"{prefix}{n}", effect, *find_lambda(lines, effect), subs)
    print(f"static const FxCase {prefix}_cases[] = {{")
    for n, effect in enumerate(names):
        print(f'  {{"{effect}", {prefix}{n}::run}},')
    print("};")


def main(argv):
    if argv[:1] == ["--all"] and len(argv) == 3:
        return all_plain(argv[1], argv[2])
    if len(argv) < 2:
        sys.exit(__doc__)
    lines = open(argv[0]).read().splitlines()
    print("// Generated by extract_lambda.py from " + argv[0].split("/")[-1] + " - do not edit.")
    for spec in argv[1:]:
        ns, effect = spec.split("=", 1)
        kind, body = find_lambda(lines, effect)
        text = "\n".join(body)
        text = text.replace('sync_offset("${mac}")', "FX_TEST_OFFSET").replace('"${mac}"', "FX_TEST_MAC")
        for target in FX_PROBES.get(effect, []):
            pat = re.compile(r"(" + re.escape(target) + r"\s*=\s*)(.+);")
            text, n = pat.subn(lambda m: f'{m.group(1)}fx_probe("{target}", {m.group(2)});', text)
            if n == 0:
                sys.exit(f"extract_lambda: probe '{target}' matched nothing in '{effect}'")
        sig = "FxIt &it, Color current_color, bool initial_run" if kind == "addressable_lambda" else "bool initial_run"
        print(f"namespace {ns} {{\n// {effect}\ninline void run({sig}) {{\n{text}\n}}\n}}  // namespace {ns}\n")


if __name__ == "__main__":
    main(sys.argv[1:])
